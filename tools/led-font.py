# Lowercase accents ride on the two rows above the x-height.
ACCENTS = {"acute": ["...#.", "..#.."], "grave": [".#...", "..#.."], "circumflex": ["..#..", ".#.#."],
           "diaeresis": [".#.#.", "....."], "tilde": [".##.#", "#.##."]}
for char, (base, accent) in {
    "à": ("a", "grave"), "â": ("a", "circumflex"), "ä": ("a", "diaeresis"),
    "è": ("e", "grave"), "é": ("e", "acute"), "ê": ("e", "circumflex"), "ë": ("e", "diaeresis"),
    "ñ": ("n", "tilde"), "ô": ("o", "circumflex"), "ö": ("o", "diaeresis"),
    "ù": ("u", "grave"), "û": ("u", "circumflex"), "ü": ("u", "diaeresis"),
}.items():
    GLYPHS[char] = ACCENTS[accent] + GLYPHS[base][2:]
GLYPHS["î"] = [".#.", "#.#"] + GLYPHS["i"][2:]
GLYPHS["ï"] = ["#.#", "..."] + GLYPHS["i"][2:]
GLYPHS["ç"] = GLYPHS["c"] + ["..#..", ".##.."]


def draw(rows, pen):
    """One rectangle a lit pixel, drawn clockwise; returns the lowest x drawn."""
    xmin = None
    for r, row in enumerate(rows):
        top = (CAP_ROWS - r) * PITCH
        for c, cell in enumerate(row):
            if cell != "#":
                continue
            x0, x1 = c * PITCH + GAP_X, (c + 1) * PITCH - GAP_X
            y0, y1 = top - PITCH + GAP_Y, top - GAP_Y
            pen.moveTo((x0, y0))
            pen.lineTo((x0, y1))
            pen.lineTo((x1, y1))
            pen.lineTo((x1, y0))
            pen.closePath()
            xmin = x0 if xmin is None else min(xmin, x0)
    return xmin or 0


def check(char, rows):
    widths = {len(row) for row in rows}
    if len(widths) != 1:
        raise SystemExit(f"{char!r}: rows of different widths {sorted(widths)}")
    if len(rows) > CAP_ROWS + 2:
        raise SystemExit(f"{char!r}: {len(rows)} rows, at most {CAP_ROWS + 2}")


def build(out):
    order, cmap, glyphs, metrics = [".notdef"], {}, {}, {}
    pen = TTGlyphPen(None)
    box = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"]
    draw(box, pen)
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (6 * PITCH, GAP_X)
    for char, rows in sorted(GLYPHS.items()):
        check(char, rows)
        name = "space" if char == " " else f"uni{ord(char):04X}"
        pen = TTGlyphPen(None)
        xmin = draw(rows, pen)
        order.append(name)
        cmap[ord(char)] = name
        glyphs[name] = pen.glyph()
        metrics[name] = ((len(rows[0]) + 1) * PITCH, xmin)

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT)
    fb.setupNameTable({
        "familyName": "B5 LED",
        "styleName": "Regular",
        "uniqueFontIdentifier": "b5-decomp-webui: B5 LED",
        "fullName": "B5 LED",
        "psName": "B5LED-Regular",
        "version": "Version 1.000",
        "copyright": "Drawn for b5-decomp-webui (MIT License).",
    })
    fb.setupOS2(sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=0,
                usWinAscent=ASCENT, usWinDescent=DESCENT, sxHeight=5 * PITCH, sCapHeight=CAP_ROWS * PITCH,
                achVendID="B5UI", fsType=0)
    fb.setupPost()
    fb.font.flavor = "woff2"
    fb.save(str(out))
    return len(order)


